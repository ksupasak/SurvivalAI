const { withAndroidManifest, withDangerousMod, AndroidConfig } = require('expo/config-plugins');
const fs = require('fs');
const path = require('path');

/**
 * Cleartext HTTP to the public internet stays blocked, but SurvivalAI is meant
 * to work when infrastructure is down, and a self-hosted board server on a
 * local network is plain http://. This plugin writes an Android network
 * security config permitting cleartext for loopback, the emulator host and
 * mDNS `.local` names, and points the manifest at it.
 *
 * Android's config matches hostnames, not IP ranges, so there is no way to
 * allow "any 192.168.x.x" here. Self-hosters on a LAN should reach the server
 * by its `.local` name; a public board server must use https.
 *
 * The iOS half of this is `NSAllowsLocalNetworking` in app.json's ATS dict.
 */

const NETWORK_SECURITY_CONFIG = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withLocalNetworkSecurity.js — do not edit by hand. -->
<network-security-config>
    <base-config cleartextTrafficPermitted="false">
        <trust-anchors>
            <certificates src="system" />
        </trust-anchors>
    </base-config>
    <domain-config cleartextTrafficPermitted="true">
        <domain includeSubdomains="false">localhost</domain>
        <domain includeSubdomains="false">127.0.0.1</domain>
        <domain includeSubdomains="false">10.0.2.2</domain>
        <domain includeSubdomains="true">local</domain>
    </domain-config>
</network-security-config>
`;

const withNetworkSecurityConfigFile = (config) =>
  withDangerousMod(config, [
    'android',
    async (cfg) => {
      const resXmlDir = path.join(
        cfg.modRequest.platformProjectRoot,
        'app',
        'src',
        'main',
        'res',
        'xml'
      );
      fs.mkdirSync(resXmlDir, { recursive: true });
      fs.writeFileSync(
        path.join(resXmlDir, 'network_security_config.xml'),
        NETWORK_SECURITY_CONFIG
      );
      return cfg;
    },
  ]);

const withManifestReference = (config) =>
  withAndroidManifest(config, (cfg) => {
    const application = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    application.$['android:networkSecurityConfig'] = '@xml/network_security_config';
    // The config file is authoritative; leaving this true would be misleading.
    application.$['android:usesCleartextTraffic'] = 'false';
    return cfg;
  });

module.exports = (config) => withManifestReference(withNetworkSecurityConfigFile(config));
